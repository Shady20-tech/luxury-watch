"""Generate the Phase 3 placeholder routes.

Every route the header and footer link to must resolve, so the navigation is an
honest picture of the site rather than a set of 404s. Each generated page is a
real page that states which phase fills it. Kept as a script so the pages stay
byte-identical and the metadata pattern is not copy-pasted by hand.
"""

import os

ROOT = 'src/app/(site)'

# (route, title, eyebrow, intro, phase — lowercase, no trailing period)
PAGES = [
    ('collections/all', 'The Collection', 'Shop', 'Browse every timepiece we have in stock.',
     'the catalogue and discovery phase (Phase 5), which adds filtering, sorting and pagination'),
    ('brands', 'Brands', 'Shop', 'The houses we carry, and the model families within each.',
     'the catalogue and discovery phase (Phase 5), which builds the brand index from the database'),
    ('search', 'Search', 'Shop', 'Search by brand, model, reference number or keyword.',
     'the catalogue and discovery phase (Phase 5), which adds database-backed search'),
    ('pages/about', 'About Us', 'The Boutique', 'Who we are and how we work.',
     'the content and service-flows phase (Phase 11)'),
    ('pages/faq', 'Frequently Asked Questions', 'Help', 'Answers on buying, selling, shipping and servicing.',
     'the content and service-flows phase (Phase 11), which renders these from the database'),
    ('pages/shipping', 'Shipping', 'Policies', 'How we deliver, insure and track a timepiece.',
     'the content phase (Phase 11)'),
    ('pages/warranty', 'Returns & Warranty', 'Policies', 'Our returns window and what our warranty covers.',
     'the content phase (Phase 11)'),
    ('pages/terms', 'Terms of Use', 'Policies', 'The terms on which this site and our sales operate.',
     'the content phase (Phase 11)'),
    ('pages/privacy', 'Privacy Policy', 'Policies', 'What personal data we hold and how we handle it.',
     'the content phase (Phase 11)'),
    ('services/sell-trade', 'Sell or Trade', 'Services', 'Sell us your watch or trade it against another.',
     'the service-flows phase (Phase 11)'),
    ('services/sourcing', 'Watch Sourcing', 'Services', 'Looking for a specific reference? We will find it.',
     'the service-flows phase (Phase 11)'),
    ('services/repair-restoration', 'Repair & Restoration', 'Services', 'Servicing, repair and restoration by our watchmakers.',
     'the service-flows phase (Phase 11)'),
    ('contact', 'Contact', 'The Boutique', 'Ask about a piece, book an appointment or start a service request.',
     'the service-flows phase (Phase 11)'),
    ('cart', 'Your Cart', 'Shop', 'The timepieces you have set aside.',
     'the cart and order-request phase (Phase 7)'),
    ('wishlist', 'Your Wishlist', 'Account', 'Timepieces you have saved for later.',
     'the product and wishlist phase (Phase 6)'),
    ('account', 'Your Account', 'Account', 'Your orders, requests and saved pieces.',
     'the authentication phase (Phase 4) and the account area (Phase 9)'),
]

TEMPLATE = """import type {{ Metadata }} from 'next';

import {{ PlannedPage }} from '@/components/chrome/planned-page';
import {{ buildMetadata }} from '@/lib/seo/metadata';

/**
 * Placeholder route. Content arrives with {phase}.
 *
 * Generated by `scripts/generate-placeholder-routes.py`. The route exists so the
 * navigation is complete; `noindex` keeps a thin page out of search results until
 * it has real content.
 */
export const metadata: Metadata = buildMetadata({{
  title: '{title}',
  description: '{description}',
  path: '/{route}',
  robots: {{ index: false, follow: true }},
}});

export default function Page() {{
  return (
    <PlannedPage
      eyebrow="{eyebrow}"
      title="{title}"
      intro="{intro}"
      phase="{phase}"
    />
  );
}}
"""


def main() -> None:
    written = 0
    for route, title, eyebrow, intro, phase in PAGES:
        target = os.path.join(ROOT, route, 'page.tsx')
        os.makedirs(os.path.dirname(target), exist_ok=True)
        description = f'{intro} This page is scheduled for {phase}.'
        content = TEMPLATE.format(
            title=title,
            eyebrow=eyebrow,
            intro=intro,
            description=description,
            phase=phase,
            route=route,
        )
        with open(target, 'w', encoding='utf-8') as handle:
            handle.write(content)
        written += 1
    print(f'wrote {written} placeholder routes')


if __name__ == '__main__':
    main()
